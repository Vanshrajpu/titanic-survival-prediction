@st.cache_resource
def load_model():

    url = (
        "https://raw.githubusercontent.com/"
        "datasciencedojo/datasets/master/titanic.csv"
    )

    df = pd.read_csv(url)

    # Gender encoding
    df["Sex"] = df["Sex"].map({
        "male": 0,
        "female": 1
    })

    # Fill missing age
    df["Age"] = df["Age"].fillna(
        df["Age"].median()
    )

    # Fill missing Embarked
    df["Embarked"] = df["Embarked"].fillna("S")

    # One-hot encoding
    df = pd.get_dummies(
        df,
        columns=["Embarked"]
    )

    # Make sure columns exist
    for column in [
        "Embarked_C",
        "Embarked_Q",
        "Embarked_S"
    ]:

        if column not in df.columns:
            df[column] = 0

    # Features
    X = df[
        [
            "Pclass",
            "Sex",
            "Age",
            "SibSp",
            "Parch",
            "Fare",
            "Embarked_Q",
            "Embarked_S"
        ]
    ]

    # Target
    y = df["Survived"]

    # Random Forest
    model = RandomForestClassifier(
        n_estimators=150,
        random_state=42
    )

    model.fit(X, y)

    return model


model = load_model()


